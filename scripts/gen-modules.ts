import { globSync, readFileSync, writeFileSync } from "node:fs";
import { join, posix, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT_DIR = join(ROOT, "apps", "api", "src");
const OUT_FILE = join(OUT_DIR, "modules.gen.ts");
const HEADER = "// GENERATED by scripts/gen-modules.ts — do not edit.";
export const OUT_OF_DATE_MESSAGE =
  "apps/api/src/modules.gen.ts is out of date — run pnpm gen:modules";

/** `../../../modules/my-tasks/src/server.ts` → `myTasks`. */
function identifier(serverFile: string): string {
  const dir = serverFile.split("/").at(-3) ?? "";
  const camel = dir.replace(/[^A-Za-z0-9]+(.)?/g, (_m, c: string = "") =>
    c.toUpperCase(),
  );
  return /^[0-9]/.test(camel) ? `_${camel}` : camel;
}

/** Renders apps/api/src/modules.gen.ts. Paths are relative to apps/api/src. */
export function renderModulesFile(serverFiles: string[]): string {
  const files = [...serverFiles].sort();
  const names = files.map(identifier);
  const imports = files.map(
    (f, i) => `import ${names[i]} from "${f.replace(/\.ts$/, "")}";\n`,
  );
  const oneLine = `export const serverModules = [${names.join(", ")}] as const;`;
  // Matches Biome's formatting so the generated file passes `biome check`.
  const list =
    oneLine.length <= 80
      ? oneLine
      : `export const serverModules = [\n${names.map((n) => `  ${n},\n`).join("")}] as const;`;
  return `${HEADER}\n${imports.join("")}\n${list}\n`;
}

function serverFiles(): string[] {
  return globSync("modules/*/src/server.ts", { cwd: ROOT }).map((f) =>
    relative(OUT_DIR, join(ROOT, f)).split(/[\\/]/).join(posix.sep),
  );
}

function main(): void {
  const next = renderModulesFile(serverFiles());
  let current: string | undefined;
  try {
    current = readFileSync(OUT_FILE, "utf8");
  } catch {
    current = undefined;
  }
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error(OUT_OF_DATE_MESSAGE);
      process.exit(1);
    }
    return;
  }
  if (current !== next) writeFileSync(OUT_FILE, next);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  main();
