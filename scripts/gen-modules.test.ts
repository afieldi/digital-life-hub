import { describe, expect, it } from "vitest";
import { renderModulesFile } from "./gen-modules";

describe("renderModulesFile", () => {
  const out = renderModulesFile([
    "../../../modules/b/src/server.ts",
    "../../../modules/a/src/server.ts",
  ]);

  it("starts with the generated header", () => {
    expect(
      out.startsWith("// GENERATED by scripts/gen-modules.ts — do not edit.\n"),
    ).toBe(true);
  });

  it("imports each module without the .ts extension, sorted", () => {
    const a = out.indexOf('import a from "../../../modules/a/src/server";');
    const b = out.indexOf('import b from "../../../modules/b/src/server";');
    expect(a).toBeGreaterThan(-1);
    expect(b).toBeGreaterThan(a);
    expect(out).not.toContain('.ts"');
    expect(out).toContain("export const serverModules = [a, b] as const;");
  });

  it("turns module directory names into identifiers", () => {
    expect(
      renderModulesFile(["../../../modules/my-tasks/src/server.ts"]),
    ).toContain('import myTasks from "../../../modules/my-tasks/src/server";');
  });

  it("renders an empty list", () => {
    expect(renderModulesFile([])).toContain(
      "export const serverModules = [] as const;",
    );
  });
});
