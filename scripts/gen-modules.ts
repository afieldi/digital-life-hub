import { globSync, readFileSync, writeFileSync } from "node:fs";
import { join, posix, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const HEADER = "// GENERATED by scripts/gen-modules.ts — do not edit.";
/** The server modules, for the API. */
const SERVER_OUT = join(ROOT, "apps", "api", "src", "modules.gen.ts");
/** The module descriptions (no server code), for the agent worker and runner. */
const DESCRIPTIONS_OUT = join(
  ROOT,
  "packages",
  "agent-protocol",
  "src",
  "modules.gen.ts",
);

/** `../../../modules/my-tasks/src/server.ts` → `myTasks`. */
function identifier(file: string): string {
  const dir = file.split("/").at(-3) ?? "";
  const camel = dir.replace(/[^A-Za-z0-9]+(.)?/g, (_m, c: string = "") =>
    c.toUpperCase(),
  );
  return /^[0-9]/.test(camel) ? `_${camel}` : camel;
}

/** `export const <name> = [...] as const;`, wrapped the way Biome formats it. */
function list(name: string, items: string[]): string {
  const oneLine = `export const ${name} = [${items.join(", ")}] as const;`;
  return oneLine.length <= 80
    ? oneLine
    : `export const ${name} = [\n${items.map((n) => `  ${n},\n`).join("")}] as const;`;
}

const importPath = (f: string) => f.replace(/\.ts$/, "");

/** Renders apps/api/src/modules.gen.ts. Paths are relative to apps/api/src. */
export function renderModulesFile(serverFiles: string[]): string {
  const files = [...serverFiles].sort();
  const names = files.map(identifier);
  const imports = files.map(
    (f, i) => `import ${names[i]} from "${importPath(f)}";\n`,
  );
  return `${HEADER}\n${imports.join("")}\n${list("serverModules", names)}\n`;
}

/**
 * Renders packages/agent-protocol/src/modules.gen.ts: each module's
 * `<id>Module` description from its `src/module.ts`. Paths are relative to
 * packages/agent-protocol/src.
 */
export function renderDescriptionsFile(moduleFiles: string[]): string {
  const files = [...moduleFiles].sort();
  const names = files.map((f) => `${identifier(f)}Module`);
  const imports = files.map(
    (f, i) => `import { ${names[i]} } from "${importPath(f)}";\n`,
  );
  return `${HEADER}\n${imports.join("")}\n${list("moduleDescriptions", names)}\n`;
}

/** The out-of-date message for each generated file whose content would change. */
export function outOfDate(
  files: { path: string; current: string | undefined; next: string }[],
): string[] {
  return files
    .filter((f) => f.current !== f.next)
    .map((f) => `${f.path} is out of date — run pnpm gen:modules`);
}

function moduleFiles(name: "server" | "module", outFile: string): string[] {
  const outDir = join(outFile, "..");
  return globSync(`modules/*/src/${name}.ts`, { cwd: ROOT }).map((f) =>
    relative(outDir, join(ROOT, f)).split(/[\\/]/).join(posix.sep),
  );
}

function read(file: string): string | undefined {
  try {
    return readFileSync(file, "utf8");
  } catch {
    return undefined;
  }
}

function main(): void {
  const files = [
    {
      out: SERVER_OUT,
      next: renderModulesFile(moduleFiles("server", SERVER_OUT)),
    },
    {
      out: DESCRIPTIONS_OUT,
      next: renderDescriptionsFile(moduleFiles("module", DESCRIPTIONS_OUT)),
    },
  ].map((f) => ({
    ...f,
    path: relative(ROOT, f.out).split(/[\\/]/).join(posix.sep),
    current: read(f.out),
  }));
  if (process.argv.includes("--check")) {
    const stale = outOfDate(files);
    for (const line of stale) console.error(line);
    if (stale.length > 0) process.exit(1);
    return;
  }
  for (const f of files) if (f.current !== f.next) writeFileSync(f.out, f.next);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  main();
