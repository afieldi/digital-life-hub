import { describe, expect, it } from "vitest";
import {
  outOfDate,
  renderDescriptionsFile,
  renderModulesFile,
} from "./gen-modules";

describe("renderModulesFile", () => {
  const out = renderModulesFile([
    "../../../modules/b/src/server.ts",
    "../../../modules/a/src/server.ts",
  ]);

  it("starts with the generated header", () => {
    expect(
      out.startsWith("// GENERATED by scripts/gen-modules.ts — do not edit.\n"),
    ).toBe(true);
  });

  it("imports each module without the .ts extension, sorted", () => {
    const a = out.indexOf('import a from "../../../modules/a/src/server";');
    const b = out.indexOf('import b from "../../../modules/b/src/server";');
    expect(a).toBeGreaterThan(-1);
    expect(b).toBeGreaterThan(a);
    expect(out).not.toContain('.ts"');
    expect(out).toContain("export const serverModules = [a, b] as const;");
  });

  it("turns module directory names into identifiers", () => {
    expect(
      renderModulesFile(["../../../modules/my-tasks/src/server.ts"]),
    ).toContain('import myTasks from "../../../modules/my-tasks/src/server";');
  });

  it("renders an empty list", () => {
    expect(renderModulesFile([])).toContain(
      "export const serverModules = [] as const;",
    );
  });
});

describe("renderDescriptionsFile", () => {
  const out = renderDescriptionsFile([
    "../../../modules/requests/src/module.ts",
    "../../../modules/agent/src/module.ts",
    "../../../modules/tasks/src/module.ts",
  ]);

  it("starts with the generated header", () => {
    expect(
      out.startsWith("// GENERATED by scripts/gen-modules.ts — do not edit.\n"),
    ).toBe(true);
  });

  it("imports each module's description by name, sorted, without .ts", () => {
    const a = out.indexOf(
      'import { agentModule } from "../../../modules/agent/src/module";',
    );
    const r = out.indexOf(
      'import { requestsModule } from "../../../modules/requests/src/module";',
    );
    expect(a).toBeGreaterThan(-1);
    expect(r).toBeGreaterThan(a);
    expect(out).not.toContain('.ts"');
  });

  it("breaks a long list one per line, as Biome does", () => {
    expect(out).toContain(
      "export const moduleDescriptions = [\n  agentModule,\n  requestsModule,\n  tasksModule,\n] as const;\n",
    );
  });

  it("keeps a short list on one line", () => {
    expect(
      renderDescriptionsFile(["../../../modules/a/src/module.ts"]),
    ).toContain("export const moduleDescriptions = [aModule] as const;");
  });

  it("renders an empty list", () => {
    expect(renderDescriptionsFile([])).toContain(
      "export const moduleDescriptions = [] as const;",
    );
  });
});

describe("outOfDate", () => {
  it("names each generated file that differs", () => {
    expect(
      outOfDate([
        { path: "apps/api/src/modules.gen.ts", current: "x", next: "x" },
        {
          path: "packages/agent-protocol/src/modules.gen.ts",
          current: undefined,
          next: "y",
        },
      ]),
    ).toEqual([
      "packages/agent-protocol/src/modules.gen.ts is out of date — run pnpm gen:modules",
    ]);
  });
});
